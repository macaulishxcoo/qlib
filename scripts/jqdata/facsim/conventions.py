# ---- B6. 参数推断 ------------------------------------------------------------
# 因子 code 里尾随的数字即窗口参数；上面这些族按此规则解析。
# 注意 \d{1,3}：MAC5 / EMA5 只有 1 位数字，若写成 \d{2,3} 会漏掉。
_WINDOW_RE = re.compile(r"^(?P<base>[A-Za-z_]+?)(?P<n>\d{1,3})$")
# 少数 code 的窗口不遵循「尾部数字」规则，需显式登记
WINDOW_OVERRIDES: dict[str, int] = {
    "single_day_VPT_6": 6,
    "single_day_VPT_12": 12,
}


def infer_window(code: str) -> int | None:
    """从因子 code 解析窗口参数（B6）。

    >>> infer_window("MAC5"), infer_window("CCI15"), infer_window("VEMA26")
    (5, 15, 26)
    >>> infer_window("boll_down") is None
    True
    """
    if code in WINDOW_OVERRIDES:
        return WINDOW_OVERRIDES[code]
    m = _WINDOW_RE.match(code)
    if m:
        n = int(m.group("n"))
        if 2 <= n <= 500:
            return n
    return None


